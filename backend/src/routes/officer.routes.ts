import { Router } from 'express';
import { UserRole } from '@prisma/client';
import * as t from '../controllers/tender.controller.js';
import * as a from '../controllers/application.controller.js';
import { requireAuth, requireRole } from '../middleware/auth.js';
import { validate } from '../middleware/validation.js';
import { asyncHandler } from '../utils/async-handler.js';
import * as tv from '../validators/tender.js';
import * as av from '../validators/application.js';
import * as d from '../controllers/document.controller.js';
import * as dv from '../validators/document.js';
import * as td from '../controllers/tender-document.controller.js';
import { singleDocumentUpload } from '../middleware/document-upload.js';
const router=Router(); router.use(requireAuth,requireRole(UserRole.OFFICER));
router.post('/tenders',validate(tv.tenderCreateSchema),asyncHandler(t.create));
router.get('/tenders',asyncHandler(t.list));
router.get('/tenders/:id',asyncHandler(t.get));
router.patch('/tenders/:id',validate(tv.tenderPatchSchema),asyncHandler(t.patch));
router.post('/tenders/:id/publish',asyncHandler(t.publish));
router.post('/tenders/:id/close',asyncHandler(t.close));
router.delete('/tenders/:id',asyncHandler(t.remove));
router.post('/tenders/:tenderId/requirements',validate(tv.requirementCreateSchema),asyncHandler(t.addRequirement));
router.get('/tenders/:tenderId/requirements',asyncHandler(t.requirements));
router.patch('/requirements/:id',validate(tv.requirementPatchSchema),asyncHandler(t.patchRequirement));
router.delete('/requirements/:id',validate(tv.requirementDeleteSchema),asyncHandler(t.deleteRequirement));
router.post('/tenders/:tenderId/documents',singleDocumentUpload,asyncHandler(td.create));
router.get('/tenders/:tenderId/documents',asyncHandler(td.officerList));
router.get('/tender-documents/:id/view',validate(dv.documentIdSchema),asyncHandler(td.officerView));
router.get('/tender-documents/:id/download',validate(dv.documentIdSchema),asyncHandler(td.officerDownload));
router.delete('/tender-documents/:id',validate(dv.documentIdSchema),asyncHandler(td.remove));
router.get('/tenders/:tenderId/applications',asyncHandler(a.officerList));
router.get('/documents/:id/view',validate(dv.documentIdSchema),asyncHandler(d.officerView));
router.get('/documents/:id/download',validate(dv.documentIdSchema),asyncHandler(d.officerDownload));
router.get('/applications/:id',validate(av.applicationIdSchema),asyncHandler(a.officerGet));
router.post('/applications/:id/accept',validate(av.applicationIdSchema),asyncHandler(a.accept));
router.post('/applications/:id/reject',validate(av.rejectSchema),asyncHandler(a.reject));
router.post('/applications/:id/blacklist',validate(av.blacklistSchema),asyncHandler(a.blacklist));
export default router;
